package com.quancrypt.analyzer.golden;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.fail;

import com.quancrypt.analyzer.domain.model.AnalysisRoot;
import com.quancrypt.analyzer.domain.model.CanonicalNames;
import com.quancrypt.analyzer.domain.model.CryptoUsage;
import com.quancrypt.analyzer.domain.model.ProjectDescriptor;
import com.quancrypt.analyzer.domain.model.ProjectType;
import com.quancrypt.analyzer.fake.FixedIds;
import com.quancrypt.analyzer.infrastructure.cbom.CycloneDxCbomWriter;
import com.quancrypt.analyzer.infrastructure.dictionary.CanonicalDictionaryLoader;
import com.quancrypt.analyzer.infrastructure.filesystem.FileSystemSourceTreeReader;
import com.quancrypt.analyzer.infrastructure.plugin.javaspring.JavaSpringPlugins;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.Objects;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * The CBOM of the QBank reference system (P3.3): it validates against the CycloneDX 1.6 schema, every component has at
 * least one occurrence, and it equals the stored snapshot. The serial number and the time are fixed, so the document only
 * changes when the detectors or the writer change; then the snapshot is deleted, regenerated by this test (which fails once
 * to say so) and the new file is reviewed like code. It is never updated automatically.
 */
class QbankCbomSnapshotTest {

    private static final Path SNAPSHOT = Path.of(System.getProperty("quancrypt.snapshots.dir"), "qbank-cbom.json");
    private static final JsonMapper JSON = JsonMapper.builder().build();

    private static String cbom;

    @BeforeAll
    static void analyze() throws Exception {
        Path reference = Path.of(System.getProperty("quancrypt.reference.dir"));
        if (!Files.isDirectory(reference.resolve("certs/out"))) {
            throw new IllegalStateException("reference-system/certs/out is missing: run 'bash certs/generate.sh' in reference-system first");
        }
        AnalysisRoot root = new AnalysisRoot(reference.toRealPath().toString());
        CanonicalNames names = new CanonicalNames(new CanonicalDictionaryLoader().loadFromClasspath());
        List<CryptoUsage> usages = JavaSpringPlugins.standard(names).analyzeCrypto(new FileSystemSourceTreeReader().open(root));
        cbom = new CycloneDxCbomWriter(() -> Instant.parse("2026-10-14T12:00:00Z"), new FixedIds(), "1.0.0")
                .write(new ProjectDescriptor(root, ProjectType.MAVEN), usages).json();
    }

    @Test
    void theCbomValidatesAgainstTheCycloneDx16Schema() {
        assertThat(com.quancrypt.analyzer.unit.cbom.CycloneDxSchemaAccess.validate(cbom)).isEmpty();
    }

    @Test
    void everyComponentHasAtLeastOneOccurrence() {
        JsonNode bom = JSON.readTree(cbom);

        assertThat(bom.get("components").size()).isPositive();
        for (JsonNode component : bom.get("components")) {
            assertThat(component.get("evidence").get("occurrences").size()).as(component.get("bom-ref").asString()).isPositive();
        }
    }

    @Test
    void theCbomEqualsTheStoredSnapshot() throws Exception {
        String pretty = JSON.writerWithDefaultPrettyPrinter().writeValueAsString(JSON.readTree(cbom)) + "\n";
        if (!Files.exists(SNAPSHOT)) {
            Files.createDirectories(Objects.requireNonNull(SNAPSHOT.getParent()));
            Files.writeString(SNAPSHOT, pretty, StandardCharsets.UTF_8);
            fail("the snapshot " + SNAPSHOT + " did not exist and was written: review it, then run the tests again");
        }
        assertThat(pretty).isEqualTo(Files.readString(SNAPSHOT, StandardCharsets.UTF_8));
    }
}
